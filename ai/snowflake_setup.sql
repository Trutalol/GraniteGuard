-- Snowflake setup for the SOC Copilot (run once in a Snowsight SQL worksheet with Run All)
-- Two service users that sign in with key pairs, never passwords:
--   DATATHON_LOADER  writes tables (used by python -m ai.snowflake_load)
--   COPILOT_APP      read-only (used by ai/serve.py)

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS DATATHON_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE;
CREATE DATABASE IF NOT EXISTS DATATHON;
CREATE SCHEMA IF NOT EXISTS DATATHON.COPILOT;

-- read-only role + service user for the app
CREATE ROLE IF NOT EXISTS COPILOT_READER;
GRANT USAGE ON WAREHOUSE DATATHON_WH TO ROLE COPILOT_READER;
GRANT USAGE ON DATABASE DATATHON TO ROLE COPILOT_READER;
GRANT USAGE ON SCHEMA DATATHON.COPILOT TO ROLE COPILOT_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DATATHON.COPILOT TO ROLE COPILOT_READER;

CREATE USER IF NOT EXISTS COPILOT_APP
  TYPE = SERVICE DEFAULT_ROLE = COPILOT_READER DEFAULT_WAREHOUSE = DATATHON_WH;
GRANT ROLE COPILOT_READER TO ROLE ACCOUNTADMIN;
GRANT ROLE COPILOT_READER TO USER COPILOT_APP;

-- writer role + service user for loading
CREATE ROLE IF NOT EXISTS COPILOT_WRITER;
GRANT ROLE COPILOT_READER TO ROLE COPILOT_WRITER;
GRANT ALL ON SCHEMA DATATHON.COPILOT TO ROLE COPILOT_WRITER;
GRANT ROLE COPILOT_WRITER TO ROLE ACCOUNTADMIN;

CREATE USER IF NOT EXISTS DATATHON_LOADER
  TYPE = SERVICE DEFAULT_ROLE = COPILOT_WRITER DEFAULT_WAREHOUSE = DATATHON_WH;
GRANT ROLE COPILOT_WRITER TO USER DATATHON_LOADER;

